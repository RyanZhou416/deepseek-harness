/**
 * frpc run directory and configuration rendering.
 *
 * The configuration follows the established frpc transport profile: websocket
 * over TLS with the relay's CA, the shared token read from a file, the per-user
 * token in `metadatas.frpToken`, and one TCP proxy to the local DSH web port.
 * The run directory and every file in it are owner-only.
 *
 * @module dsh-relay/frpc-config
 */
import { chmod, mkdir, rm, writeFile } from 'node:fs/promises'
import { join } from 'node:path'
import { relayError } from './errors.ts'
import type { RelayTunnel } from './protocol.ts'

/** frpc run directory name below the Harness home. */
const RELAY_HOME_DIRECTORY = 'dsh-relay'

/** Shared-token file name expected beside the configuration. */
export const SHARED_TOKEN_FILE = 'frp-shared-token'

/** CA certificate file name expected beside the configuration. */
export const CA_CERTIFICATE_FILE = 'frp-ca.crt'

/** frpc configuration file name. */
export const FRPC_CONFIG_FILE = 'frpc.toml'

/** Owner-only directory mode. */
const DIRECTORY_MODE = 0o700

/** Owner-only file mode. */
const FILE_MODE = 0o600

/** Build the frpc proxy name for one user. */
export function relayProxyName(username: string): string {
  return `dsh-${username}`
}

/** Inputs of one rendered frpc configuration. */
export interface FrpcConfigInput {
  /** Tunnel parameters returned by the relay. */
  readonly tunnel: RelayTunnel
  /** Signed-in username, used for the proxy name. */
  readonly username: string
  /** Local DSH web port. */
  readonly localPort: number
  /** Absolute path of the shared-token file. */
  readonly sharedTokenPath: string
  /** Absolute path of the CA certificate file. */
  readonly caCertificatePath: string
}

function tomlString(value: string): string {
  return JSON.stringify(value)
}

/**
 * Render the frpc configuration for one tunnel.
 * @param input - tunnel, username, local port, and the absolute token/CA paths.
 * @returns the TOML document, newline-terminated.
 */
export function renderFrpcConfig(input: FrpcConfigInput): string {
  if (!Number.isSafeInteger(input.localPort) || input.localPort < 1 || input.localPort > 65_535) {
    throw relayError('web-server-unavailable', 'the DSH web server has not bound a TCP port yet')
  }
  const tunnel = input.tunnel
  const lines = [
    '# Generated by dsh-relay for one connection; rewritten on every connect.',
    `serverAddr = ${tomlString(tunnel.serverAddr)}`,
    `serverPort = ${String(tunnel.serverPort)}`,
    'loginFailExit = false',
    '',
    `user = ${tomlString(tunnel.user)}`,
    `metadatas.frpToken = ${tomlString(tunnel.frpToken)}`,
    '',
    'auth.method = "token"',
    'auth.additionalScopes = ["HeartBeats", "NewWorkConns"]',
    'auth.tokenSource.type = "file"',
    `auth.tokenSource.file.path = ${tomlString(input.sharedTokenPath)}`,
    '',
    'transport.protocol = "websocket"',
    'transport.wireProtocol = "v2"',
    `transport.websocket.path = ${tomlString(tunnel.websocketPath)}`,
    'transport.tls.enable = true',
    `transport.tls.trustedCaFile = ${tomlString(input.caCertificatePath)}`,
    `transport.tls.serverName = ${tomlString(tunnel.tlsServerName)}`,
    'transport.heartbeatInterval = 10',
    'transport.heartbeatTimeout = 30',
    'transport.tcpMux = true',
    'transport.tcpMuxKeepaliveInterval = 30',
    'transport.poolCount = 32',
    '',
    'log.to = "console"',
    'log.level = "info"',
    'log.disablePrintColor = true',
    '',
    '[[proxies]]',
    `name = ${tomlString(relayProxyName(input.username))}`,
    'type = "tcp"',
    'localIP = "127.0.0.1"',
    `localPort = ${String(input.localPort)}`,
    `remotePort = ${String(tunnel.remotePort)}`,
    'transport.useEncryption = false',
    'transport.useCompression = false',
    '',
  ]
  return lines.join('\n')
}

/**
 * Create one directory if needed and restrict it to the current user.
 * @param path - directory path.
 */
export async function ensurePrivateDirectory(path: string): Promise<void> {
  await mkdir(path, { recursive: true, mode: DIRECTORY_MODE })
  await chmod(path, DIRECTORY_MODE).catch(() => {
    // Windows has no POSIX mode bits; the filesystem ACL is the owner boundary.
  })
}

/**
 * Write one owner-only file, replacing any existing file.
 *
 * The previous file is removed first and the new one is created exclusively, so
 * a pre-existing link cannot redirect the write.
 * @param path - target file path.
 * @param content - UTF-8 content.
 */
export async function writePrivateFile(path: string, content: string): Promise<void> {
  await writePrivateBytes(path, Buffer.from(content, 'utf8'))
}

/**
 * Write one owner-only binary file, replacing any existing file.
 * @param path - target file path.
 * @param content - file bytes.
 */
export async function writePrivateBinaryFile(path: string, content: Uint8Array): Promise<void> {
  await writePrivateBytes(path, content)
}

async function writePrivateBytes(path: string, content: Uint8Array): Promise<void> {
  await rm(path, { force: true })
  await writeFile(path, content, { mode: FILE_MODE, flag: 'wx' })
  await chmod(path, FILE_MODE).catch(() => {
    // Windows has no POSIX mode bits; the filesystem ACL is the owner boundary.
  })
}

/** Absolute paths of the files one connection writes. */
export interface RelayRunFiles {
  /** Run directory holding every generated file. */
  readonly runDirectory: string
  /** frpc configuration path. */
  readonly configPath: string
  /** Shared-token file path. */
  readonly sharedTokenPath: string
  /** CA certificate file path. */
  readonly caCertificatePath: string
}

/**
 * Run directory for one Harness home.
 * @param home - absolute Harness home.
 * @returns `<home>/dsh-relay/run`.
 */
export function relayRunDirectory(home: string): string {
  return join(home, RELAY_HOME_DIRECTORY, 'run')
}

/**
 * Write the configuration, shared token, and CA certificate for one connection.
 * @param runDirectory - owner-only run directory.
 * @param input - tunnel, user, and local port.
 * @returns the absolute paths of the written files.
 */
export async function writeRelayRunFiles(
  runDirectory: string,
  input: { tunnel: RelayTunnel; username: string; localPort: number },
): Promise<RelayRunFiles> {
  await ensurePrivateDirectory(runDirectory)
  const configPath = join(runDirectory, FRPC_CONFIG_FILE)
  const sharedTokenPath = join(runDirectory, SHARED_TOKEN_FILE)
  const caCertificatePath = join(runDirectory, CA_CERTIFICATE_FILE)
  const config = renderFrpcConfig({
    tunnel: input.tunnel,
    username: input.username,
    localPort: input.localPort,
    sharedTokenPath,
    caCertificatePath,
  })
  await writePrivateFile(sharedTokenPath, `${input.tunnel.sharedToken}\n`)
  await writePrivateFile(caCertificatePath, `${input.tunnel.caPem.trim()}\n`)
  await writePrivateFile(configPath, config)
  return { runDirectory, configPath, sharedTokenPath, caCertificatePath }
}
